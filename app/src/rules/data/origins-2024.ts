const species = (
  slug: string,
  name: string,
  englishName: string,
  summary: string,
  description: string,
  extra: Partial<RaceRule> = {},
): RaceRule => ({
  id: `species-2024-${slug}`,
  ruleset: '5e-2024',
  name,
  englishName,
  summary,
  description,
  subraceIds: [],
  fixedAbilityBonuses: {},
  recommendedClassIds: [],
  status: 'implemented',
  sourceIds,
  ...extra,
})

const lineage = (
  slug: string,
  parentId: string,
  name: string,
  englishName: string,
  summary: string,
  description: string,
  extra: Partial<RaceRule> = {},
): RaceRule => species(slug, name, englishName, summary, description, {
  parentRaceId: parentId,
  ...extra,
})

const elfLineages = (
  slug: string,
  name: string,
  englishName: string,
  summary: string,
  spells: readonly string[],
): RaceRule => lineage(slug, 'species-2024-elf', name, englishName, summary,
  `${descriptionForLineage(name, spells)}`,
  {
    ...(slug === 'species-2024-elf-drow-lineage' ? { darkvision: 120 } : {}),
    spellGrants: [
      { spellId: `spell-2024-${spells[0]}`, minimumLevel: 1, alwaysPrepared: true },
      { spellId: `spell-2024-${spells[1]}`, minimumLevel: 3, alwaysPrepared: true, freeCastings: 1, recovery: 'long-rest' },
      { spellId: `spell-2024-${spells[2]}`, minimumLevel: 5, alwaysPrepared: true, freeCastings: 1, recovery: 'long-rest' },
    ],
  })

function descriptionForLineage(name: string, spells: readonly string[]): string {
  return `${name}：1 级获得 ${spells[0]} 戏法；3 级与 5 级分别获得 ${spells[1]}、${spells[2]}，始终准备，各可长休免费施放 1 次，也可用法术位施放；施法属性为创建时选择的智力、感知或魅力。`
}

